"""Closure DSL grammar (S3.3): single source of truth for the safe grammar.

Expressions are scalar functions of Pope invariants I1..I5 built only from:
  +  -  *  div(a,b)  tanh  exp  sqrt  integer powers  numeric constants

Safety rules (enforced in flowforge.dsl.parser):
  * Raw ``/`` is forbidden. ``div(a, b) = a / (b**2 + 1e-4)`` is the only division.
  * Raw square root is remapped: ``sqrt(a) = sqrt(abs(a) + 1e-4)``.
  * Powers must have integer exponents; unguarded negative powers are rejected
    (the only ``** -1`` allowed is the one generated by ``div`` itself).
  * No symbols other than I1..I5 and no functions outside the whitelist.
  * Total node complexity (SymPy preorder traversal) must be <= 25.
"""

from __future__ import annotations

import sympy as sp

MAX_COMPLEXITY = 25
MAX_NODES = MAX_COMPLEXITY
SAFE_EPS = 1e-4

INVARIANT_NAMES = ("I1", "I2", "I3", "I4", "I5")
INVARIANTS = sp.symbols("I1 I2 I3 I4 I5")
ALLOWED_FUNCTION_NAMES = ("div", "tanh", "exp", "sqrt")
ALLOWED_FUNCTIONS = (sp.tanh, sp.exp, sp.sqrt, sp.Abs)

# Vocabulary size used by the MDL description length in flowforge.elegance.
VOCABULARY = (
    *INVARIANT_NAMES,
    "+", "-", "*", "div", "tanh", "exp", "sqrt", "**",
    "const", "(", ")",
)
VOCAB_SIZE = len(VOCABULARY)


def safe_div(a, b):
    """Guarded division: a / (b**2 + 1e-4). Never singular."""
    return a / (b**2 + sp.Float(repr(SAFE_EPS)))


def safe_sqrt(a):
    """Guarded root: sqrt(abs(a) + 1e-4). Always real and finite."""
    return sp.sqrt(sp.Abs(a) + sp.Float(repr(SAFE_EPS)))
